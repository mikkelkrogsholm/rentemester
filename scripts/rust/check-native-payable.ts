import type { Page } from "@playwright/test";
import { readFileSync,writeFileSync } from "node:fs";
const evidencePath="/tmp/rentemester-rust-reports/native-payable.json";
export async function checkNativePayable(page:Page,base:string,reopened=false){
 const url=`${base}/api/companies/synthetic`;
 const headers={origin:base,"content-type":"application/json"};
 let evidence:{id:number;document:number;original:string};
 if(!reopened){
  await page.goto(`${base}/companies/synthetic/kontoplan`);
  const form=page.getByRole("form",{name:"Opret konto",exact:true});
  await form.getByLabel("Kontonummer",{exact:true}).fill("7000");
  await form.getByLabel("Kontonavn",{exact:true}).fill("Synthetic trade creditors");
  await form.getByLabel(/^Kontotype/).selectOption("liability");
  await form.getByLabel(/^Normal saldo/).selectOption("credit");
  await form.getByRole("button",{name:"Opret konto",exact:true}).click();
  await page.getByRole("cell",{name:"Synthetic trade creditors",exact:true}).waitFor();
  const role=page.getByRole("form",{name:"Bekræft kontorolle",exact:true});
  await role.getByLabel(/^Kontorolle/).selectOption("creditors");
  await role.getByLabel(/^Konto til rollen/).selectOption("7000");
  await role.getByRole("button",{name:"Bekræft kontorolle",exact:true}).click();
  await page.getByRole("row").filter({hasText:"Kreditorer"}).getByText(/Konto 7000/).waitFor();
  await page.goto(`${base}/companies/synthetic/bilag`);
  await page.getByRole("button",{name:"Indlæs bilag",exact:true}).click();
  const upload=page.getByRole("dialog");
  await upload.getByLabel("Bilagsfil",{exact:true}).setInputFiles({name:"synthetic-unpaid-invoice.txt",mimeType:"text/plain",buffer:Buffer.from("Synthetic unpaid invoice SYN-UNPAID-1; net DKK 1000; VAT 250; gross 1250\n")});
  const today=new Date().toISOString().slice(0,10);
  await upload.getByLabel(/^Udfyld fra leverandør/).selectOption({label:"Synthetic Updated Supplier"});
  for(const [label,value] of Object.entries({"Bilagsdato":today,"Fakturanr. (valgfri)":"SYN-UNPAID-1","Beløb inkl. moms":"1250,00","Momsbeløb":"250,00","Beskrivelse af leverance":"Synthetic unpaid supplies","Modtager":"Synthetic Company","Modtager CVR/moms":"DK87654321","Modtageradresse":"Synthetic Street 1"})) await upload.getByLabel(label,{exact:true}).fill(value);
  await upload.getByRole("button",{name:"Indlæs bilag",exact:true}).click();
  await upload.getByText(/Bilaget er indlæst som DOC-/).waitFor();
  await upload.getByRole("button",{name:"Luk",exact:true}).click();
  const docs=await(await page.request.get(`${url}/documents`)).json();
  const document=docs.documents.documents.find((d:{filename:string})=>d.filename==="synthetic-unpaid-invoice.txt");
  const original=await page.request.get(`${url}/documents/${document.id}/file`);
  await page.goto(`${base}/companies/synthetic/leverandoerfaktura`);
  await page.getByRole("button",{name:"Registrér leverandørfaktura",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByLabel("Vælg bilag",{exact:true}).selectOption(String(document.id));
  await dialog.getByLabel("Vælg udgiftskonto",{exact:true}).selectOption("3100");
  await dialog.getByLabel("Vælg momsbehandling",{exact:true}).selectOption("standard");
  await dialog.getByLabel("Vælg leverandør",{exact:true}).selectOption({label:"Synthetic Updated Supplier"});
  await dialog.getByLabel("Forfaldsdato",{exact:true}).fill(today);
  const [registered]=await Promise.all([page.waitForResponse(r=>r.url().endsWith("/payables")&&r.request().method()==="POST"),dialog.getByRole("button",{name:"Registrér leverandørfaktura",exact:true}).click()]);
  const result=await registered.json();if(!registered.ok()) throw new Error(`Payable registration failed: ${JSON.stringify(result)}`);
  await dialog.waitFor({state:"hidden"});
  evidence={id:result.payable.payableId,document:document.id,original:(await original.body()).toString("base64")};
  const before=await(await page.request.get(`${url}/payables?status=all`)).json();
  if(before.payables.totalOpenBalance!==1250||before.payables.rows[0].paidAmount!==0)throw new Error("Unpaid bill not recognized");
  const trial=await(await page.request.get(`${url}/trial-balance`)).json();
  if(trial.trialBalance.rows.find((a:{accountNo:string})=>a.accountNo==="7000")?.credit!==1250) throw new Error("No supplier debt recognized");
  const duplicate=await page.request.post(`${url}/payables`,{headers,data:{documentId:document.id,billDate:today,dueDate:today,expenseAccountNo:"3100",confirm:true}});
  if(duplicate.status()!==422)throw new Error("Purchase bill registered twice");
  await page.goto(`${base}/companies/synthetic/bank`);
  await page.getByRole("button",{name:"Importér kontoudtog",exact:true}).click();
  const bank=page.getByRole("dialog");
  await bank.getByLabel("CSV-fil",{exact:true}).setInputFiles({name:"synthetic-payable-payments.csv",mimeType:"text/csv",buffer:Buffer.from(`date;text;amount;currency;reference\n${today};Synthetic supplier partial;-500;DKK;synthetic-payable-one\n${today};Synthetic supplier final;-750;DKK;synthetic-payable-two\n`)});
  await bank.getByLabel(/^Bankkonto \(valgfri\)/).fill("synthetic-operating-bank");
  await bank.getByRole("button",{name:"Importér",exact:true}).click();
  await bank.getByText(/2 transaktioner importeret/).waitFor();
  await bank.getByRole("button",{name:"Luk",exact:true}).click();
  const imported=await(await page.request.get(`${url}/bank`)).json();
  for(const [text,remaining] of [["Synthetic supplier partial",750],["Synthetic supplier final",0]] as const){
   const transaction=imported.bank.transactions.find((t:{text:string})=>t.text===text);
   await page.goto(`${base}/companies/synthetic/leverandoerfaktura`);
   await page.getByRole("row").filter({hasText:"SYN-UNPAID-1"}).getByRole("button",{name:"Markér betalt",exact:true}).click();
   const confirm=page.getByRole("dialog");
   await confirm.getByLabel("Banktransaktions-id",{exact:true}).fill(String(transaction.id));
   const [paid]=await Promise.all([page.waitForResponse(r=>r.url().endsWith(`/payables/${evidence.id}/pay`)&&r.request().method()==="POST"),confirm.getByRole("button",{name:"Markér betalt",exact:true}).click()]);
   const applied=await paid.json();if(!paid.ok()||applied.payment.openBalance!==remaining)throw new Error(`Wrong payable settlement: ${JSON.stringify(applied)}`);
   await confirm.waitFor({state:"hidden"});
   const duplicate=await page.request.post(`${url}/payables/${evidence.id}/pay`,{headers,data:{bankTransactionId:transaction.id,confirm:true}});
   if(duplicate.status()!==422)throw new Error("Supplier payment applied twice");
  }
  writeFileSync(evidencePath,JSON.stringify(evidence));
 }else evidence=JSON.parse(readFileSync(evidencePath,"utf8"));
 const list=await(await page.request.get(`${url}/payables?status=paid`)).json();
 const row=list.payables.rows.find((p:{payableId:number})=>p.payableId===evidence.id);
 if(!row||row.status!=="paid"||row.paidAmount!==1250||row.openBalance!==0||list.payables.totalOpenBalance!==0)throw new Error(`Payable not fully settled: ${JSON.stringify(list)}`);
 const trial=await(await page.request.get(`${url}/trial-balance`)).json();
 if(!trial.trialBalance.balanced||trial.trialBalance.rows.find((a:{accountNo:string})=>a.accountNo==="7000")?.balance!==0)throw new Error("Creditor ledger not cleared");
 const report=await(await page.request.get(`${url}/income-statement`)).json();
 const vat=await(await page.request.get(`${url}/vat`)).json();
 if(report.incomeStatement.totalExpense!==2842.25||report.incomeStatement.result!==-2842.25||vat.vat.inputVat!==275||vat.vat.payable!==-275||vat.vat.vatReportErrors.length)throw new Error("Payable payments repeated expense or VAT");
 const bank=await(await page.request.get(`${url}/bank`)).json();
 if(bank.bank.transactions.length!==10||bank.bank.matchedCount!==10||bank.bank.unmatchedCount!==0||bank.bank.bookedBalance!==-3117.25)throw new Error("Payable bank reconciliation incorrect");
 const original=await page.request.get(`${url}/documents/${evidence.document}/file`);
 if(!(await original.body()).equals(Buffer.from(evidence.original,"base64")))throw new Error("Payable settlement changed purchase original");
 await page.goto(`${base}/companies/synthetic/leverandoerfaktura`);
 await page.getByRole("button",{name:"Betalte",exact:true}).click();
 await page.getByRole("row").filter({hasText:"SYN-UNPAID-1"}).getByText("Betalt",{exact:true}).waitFor();
 await page.screenshot({path:"/tmp/rentemester-rust-payable.png",fullPage:true});
 console.log(reopened?"PASS: paid supplier bill, two bank settlements, cleared original creditor, exact original and unchanged expense/VAT persist after restart":"PASS: browser unpaid supplier invoice → recognition of expense/VAT/debt → two bank payments → paid bill and cleared creditor; no duplicate booking/payment");
}
