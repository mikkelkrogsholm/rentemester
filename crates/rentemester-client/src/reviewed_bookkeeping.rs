//! Existing source-bound four-eyes workflow. No payload/hash/key/actor derivation or policy decisions.
use crate::{
    ApiClient, Error, company_path,
    domain::{body, object},
};
use reqwest::Method;
use serde_json::{Value, json};
#[derive(Clone, Copy, Debug)]
pub enum ReviewedRead {
    Queue,
    Drafts,
    Rules,
}
#[derive(Clone, Copy, Debug)]
pub enum ReviewedMutation<'a> {
    CreateBankDraft,
    Submit(&'a str),
    Reject(&'a str),
    ApprovePost(&'a str),
}
/// A single bounded path segment; the server establishes draft state and author/reviewer authority.
pub fn valid_draft_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id.as_bytes()[0].is_ascii_lowercase()
        && id
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}
pub fn reviewed_body_schema(operation: ReviewedMutation<'_>) -> Value {
    let hash = json!({"type":"string","minLength":1,"maxLength":65536,"description":"Exact server evidence string from the current canonical read; never invent or recalculate"});
    match operation {
        ReviewedMutation::CreateBankDraft => object(
            json!({"bankTransactionId":{"type":"integer","minimum":1,"maximum":9007199254740991u64},"expectedSourceHash":hash,"documentId":{"type":["integer","null"],"minimum":1,"maximum":9007199254740991u64},"accountNo":{"type":"string","minLength":1,"maxLength":128},"draftId":{"type":"string","minLength":1,"maxLength":64,"pattern":"^[a-z][a-z0-9-]*$","description":"Explicit caller-selected stable draft id; never generated by adapter"},"confirm":{"const":true}}),
            &[
                "bankTransactionId",
                "expectedSourceHash",
                "accountNo",
                "draftId",
                "confirm",
            ],
        ),
        ReviewedMutation::Submit(_) => object(
            json!({"expectedEventHash":hash,"confirm":{"const":true}}),
            &["expectedEventHash"],
        ),
        ReviewedMutation::Reject(_) => object(
            json!({"expectedEventHash":hash,"reason":{"type":"string","minLength":1,"maxLength":1000},"confirm":{"const":true}}),
            &["expectedEventHash", "reason"],
        ),
        ReviewedMutation::ApprovePost(_) => object(
            json!({"expectedEventHash":hash,"confirm":{"const":true}}),
            &["expectedEventHash", "confirm"],
        ),
    }
}
impl ApiClient {
    pub async fn reviewed_bookkeeping(
        &self,
        company: &str,
        read: ReviewedRead,
    ) -> Result<Value, Error> {
        let path = match read {
            ReviewedRead::Queue => "reviewed-bank",
            ReviewedRead::Drafts => "accounting-drafts",
            ReviewedRead::Rules => "posting-rules",
        };
        self.get(&company_path(company, path)?, &[]).await
    }
    /// Send exact body once with current cookie authority. Unknown writes require canonical reads;
    /// no automatic replay. Server alone rechecks source evidence, periods and independent reviewer.
    pub async fn mutate_reviewed_bookkeeping(
        &self,
        company: &str,
        operation: ReviewedMutation<'_>,
        bytes: Vec<u8>,
        confirmed: bool,
    ) -> Result<Value, Error> {
        if !confirmed {
            return Err(Error::InvalidInput(
                "explicit reviewed-bookkeeping confirmation required",
            ));
        }
        let route = match operation {
            ReviewedMutation::CreateBankDraft => "reviewed-bank".into(),
            ReviewedMutation::Submit(id)
            | ReviewedMutation::Reject(id)
            | ReviewedMutation::ApprovePost(id) => {
                if !valid_draft_id(id) {
                    return Err(Error::InvalidInput("bounded lowercase draft id required"));
                }
                let action = match operation {
                    ReviewedMutation::Submit(_) => "submit",
                    ReviewedMutation::Reject(_) => "reject",
                    _ => "approve-and-post",
                };
                format!("accounting-drafts/{id}/{action}")
            }
        };
        body(&bytes, &reviewed_body_schema(operation))?;
        self.request(
            Method::POST,
            &company_path(company, &route)?,
            &[],
            Some(bytes),
        )
        .await
    }
}
