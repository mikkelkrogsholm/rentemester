//! Exact reviewed batch transport. Server owns source proofs, policy, money and authority.
use crate::{
    ApiClient, Error, MAX_RESPONSE, company_path,
    domain::{body, object},
};
use reqwest::Method;
use serde_json::{Value, json};
pub const MAX_BOOKKEEPING_BATCH_BODY: usize = 32 * 1024;
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BookkeepingBatchMutation {
    Persist,
    Approve,
    Apply,
}
impl BookkeepingBatchMutation {
    pub fn suffix(self) -> &'static str {
        match self {
            Self::Persist => "persist",
            Self::Approve => "approve",
            Self::Apply => "apply",
        }
    }
}
pub fn bookkeeping_batch_scope_schema() -> Value {
    let date = json!({"type":"string","minLength":10,"maxLength":10,"description":"Explicit ISO calendar date, server validates"});
    object(
        json!({"accountingFrom":date,"accountingTo":date,"bankFrom":date,"bankTo":date,"companyId":{"type":"integer","minimum":1,"maximum":9007199254740991u64}}),
        &["accountingFrom", "accountingTo", "bankFrom", "bankTo"],
    )
}
pub fn bookkeeping_batch_body_schema(op: BookkeepingBatchMutation) -> Value {
    let hash = json!({"type":"string","minLength":64,"maxLength":64,"pattern":"^[0-9a-f]{64}$","description":"Exact reviewed server plan hash"});
    if op == BookkeepingBatchMutation::Persist {
        let mut s = bookkeeping_batch_scope_schema();
        s["properties"]["runKey"] = json!({"type":"string","minLength":1,"maxLength":1024,"description":"Explicit caller-selected stable run key; never generated by adapter"});
        s["properties"]["expectedPlanHash"] = hash;
        s["properties"]["confirm"] = json!({"const":true});
        s["required"].as_array_mut().unwrap().extend([
            json!("runKey"),
            json!("expectedPlanHash"),
            json!("confirm"),
        ]);
        s
    } else {
        object(
            json!({"runId":{"type":"integer","minimum":1,"maximum":9007199254740991u64},"planHash":hash,"confirm":{"const":true}}),
            &["runId", "planHash", "confirm"],
        )
    }
}
fn scope_query(scope: &Value) -> Result<Vec<(String, String)>, Error> {
    body(
        &serde_json::to_vec(scope).map_err(|_| Error::InvalidInput("native scope required"))?,
        &bookkeeping_batch_scope_schema(),
    )?;
    for key in ["accountingFrom", "accountingTo", "bankFrom", "bankTo"] {
        let s = scope[key].as_str().unwrap();
        if !s.bytes().enumerate().all(|(i, c)| {
            if i == 4 || i == 7 {
                c == b'-'
            } else {
                c.is_ascii_digit()
            }
        }) {
            return Err(Error::InvalidInput("explicit ISO scope dates required"));
        }
    }
    if scope["accountingFrom"].as_str() > scope["accountingTo"].as_str()
        || scope["bankFrom"].as_str() > scope["bankTo"].as_str()
    {
        return Err(Error::InvalidInput("ordered explicit scope required"));
    }
    Ok(scope
        .as_object()
        .unwrap()
        .iter()
        .map(|(k, v)| {
            (
                k.clone(),
                v.as_str()
                    .map(str::to_owned)
                    .unwrap_or_else(|| v.to_string()),
            )
        })
        .collect())
}
fn exact_id(id: i64) -> Result<(), Error> {
    if (1..=9_007_199_254_740_991).contains(&id) {
        Ok(())
    } else {
        Err(Error::InvalidInput("positive exact run ID required"))
    }
}
impl ApiClient {
    pub async fn bookkeeping_batch_plan(
        &self,
        company: &str,
        scope: &Value,
    ) -> Result<Value, Error> {
        let owned = scope_query(scope)?;
        let query = owned
            .iter()
            .map(|(k, v)| (k.as_str(), v.as_str()))
            .collect::<Vec<_>>();
        self.batch_json(
            Method::GET,
            &company_path(company, "bookkeeping-batch")?,
            &query,
            None,
        )
        .await
    }
    pub async fn bookkeeping_batch_status_by_key(
        &self,
        company: &str,
        run_key: &str,
    ) -> Result<Value, Error> {
        if run_key.trim().is_empty()
            || run_key.len() > 1024
            || run_key.chars().any(char::is_control)
        {
            return Err(Error::InvalidInput("bounded exact caller runKey required"));
        }
        self.batch_json(
            Method::GET,
            &company_path(company, "bookkeeping-batch/runs")?,
            &[("runKey", run_key)],
            None,
        )
        .await
    }
    pub async fn bookkeeping_batch_status(
        &self,
        company: &str,
        run_id: i64,
    ) -> Result<Value, Error> {
        exact_id(run_id)?;
        self.batch_json(
            Method::GET,
            &company_path(company, &format!("bookkeeping-batch/runs/{run_id}"))?,
            &[],
            None,
        )
        .await
    }
    pub async fn mutate_bookkeeping_batch(
        &self,
        company: &str,
        op: BookkeepingBatchMutation,
        bytes: Vec<u8>,
        confirmed: bool,
    ) -> Result<Value, Error> {
        if !confirmed || bytes.len() > MAX_BOOKKEEPING_BATCH_BODY {
            return Err(Error::InvalidInput(
                "explicit batch confirmation and native32KiB body required",
            ));
        }
        body(&bytes, &bookkeeping_batch_body_schema(op))?;
        let v: Value = serde_json::from_slice(&bytes)
            .map_err(|_| Error::InvalidInput("exact native batch JSON required"))?;
        let key = if op == BookkeepingBatchMutation::Persist {
            "expectedPlanHash"
        } else {
            "planHash"
        };
        if !v[key]
            .as_str()
            .unwrap_or("")
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        {
            return Err(Error::InvalidInput("exact lowercase plan SHA256 required"));
        }
        if op == BookkeepingBatchMutation::Persist {
            if v["runKey"].as_str().is_none_or(|k| {
                k.trim().is_empty() || k.len() > 1024 || k.chars().any(char::is_control)
            }) {
                return Err(Error::InvalidInput("bounded exact caller runKey required"));
            }
            let mut scope = v.clone();
            for k in ["runKey", "expectedPlanHash", "confirm"] {
                scope.as_object_mut().unwrap().remove(k);
            }
            scope_query(&scope)?;
        } else {
            exact_id(
                v["runId"]
                    .as_i64()
                    .ok_or(Error::InvalidInput("exact runId required"))?,
            )?;
        }
        self.batch_json(
            Method::POST,
            &company_path(company, &format!("bookkeeping-batch/{}", op.suffix()))?,
            &[],
            Some(bytes),
        )
        .await
    }
    async fn batch_json(
        &self,
        method: Method,
        path: &str,
        query: &[(&str, &str)],
        body: Option<Vec<u8>>,
    ) -> Result<Value, Error> {
        let mutation = body.is_some();
        let unknown = || {
            if mutation {
                Error::OutcomeUnknown
            } else {
                Error::Protocol
            }
        };
        let mut response = self
            .send(
                method,
                path,
                query,
                body,
                self.cookie.as_ref().map(|v| v.as_str()),
            )
            .await?;
        let status = response.status();
        if mutation && (status.is_server_error() || status.as_u16() == 408) {
            return Err(Error::OutcomeUnknown);
        }
        let mut bytes = Vec::new();
        while let Some(chunk) = response.chunk().await.map_err(|_| unknown())? {
            if bytes.len().saturating_add(chunk.len()) > MAX_RESPONSE {
                return Err(unknown());
            }
            bytes.extend_from_slice(&chunk);
        }
        let value: Value = serde_json::from_slice(&bytes).map_err(|_| {
            if status.is_success() {
                unknown()
            } else {
                Error::Refused {
                    status: status.as_u16(),
                }
            }
        })?;
        if value["ok"] == false && value["code"].as_str().is_some_and(|s| !s.is_empty()) {
            if mutation
                && matches!(
                    value["code"].as_str(),
                    Some("internal" | "outcome_unknown" | "outcome_unconfirmed")
                )
            {
                return Err(Error::OutcomeUnknown);
            }
            return Ok(value);
        }
        if status.is_success() && value["ok"] == true {
            Ok(value)
        } else if status.is_success() {
            Err(unknown())
        } else {
            Err(Error::Refused {
                status: status.as_u16(),
            })
        }
    }
}

impl ApiClient {
    /// Frozen original flat read grammar (company is the separately authorized selector).
    pub fn bookkeeping_workbench_schema() -> Value {
        object(json!({
            "from":{"type":"string","pattern":"^\\d{4}-\\d{2}-\\d{2}$"},
            "to":{"type":"string","pattern":"^\\d{4}-\\d{2}-\\d{2}$"},
            "status":{"type":"string","enum":["ready","suggestedMatch","missingDocument","partyUnresolved","accountingDecisionRequired","vatEvidenceRequired","dimensionEvidenceRequired","stalePlan","applyFailed"]},
            "bankAccountId":{"type":"integer","exclusiveMinimum":0,"maximum":9007199254740991u64},
            "partyId":{"type":"string","minLength":3,"maxLength":64},
            "documentQuality":{"type":"string","enum":["matched","missing"]},
            "account":{"type":"string","minLength":1,"maxLength":32},
            "vatTreatment":{"type":"string","minLength":1,"maxLength":80},
            "dimension":{"type":"string","minLength":3,"maxLength":160},
            "cursor":{"type":"integer","minimum":0,"maximum":9007199254740991u64},
            "limit":{"type":"integer","minimum":1,"maximum":100},
            "search":{"type":"string","maxLength":200}
        }), &["from", "to"])
    }
    pub fn validate_bookkeeping_workbench(input: &Value) -> Result<(), Error> {
        // Reuse the strict schema validator for unknown fields, types, enums and numbers.
        // String bounds in the original Zod grammar count UTF-16 code units.
        let mut schema = Self::bookkeeping_workbench_schema();
        for property in schema["properties"].as_object_mut().unwrap().values_mut() {
            property.as_object_mut().unwrap().remove("minLength");
            property.as_object_mut().unwrap().remove("maxLength");
        }
        let mut normalized = input.clone();
        for key in ["bankAccountId", "cursor", "limit"] {
            if let Some(n) = input[key].as_f64() {
                if n.fract() == 0.0 && (0.0..=9_007_199_254_740_991.0).contains(&n) {
                    normalized[key] = json!(n as u64);
                }
            }
        }
        body(&serde_json::to_vec(&normalized).map_err(|_| Error::InvalidInput("flat workbench required"))?, &schema)?;
        for (key, property) in Self::bookkeeping_workbench_schema()["properties"].as_object().unwrap() {
            if let Some(text) = input[key].as_str() {
                let length = text.encode_utf16().count() as u64;
                if length < property["minLength"].as_u64().unwrap_or(0)
                    || length > property["maxLength"].as_u64().unwrap_or(u64::MAX) {
                    return Err(Error::InvalidInput("workbench string outside original bounds"));
                }
            }
        }
        for key in ["from", "to"] {
            let date = input[key].as_str().unwrap();
            if date.len() != 10 || !date.bytes().enumerate().all(|(i,b)| if i==4 || i==7 { b==b'-' } else { b.is_ascii_digit() }) {
                return Err(Error::InvalidInput("ISO workbench date shape required"));
            }
        }
        // Calendar validity/order are business checks on the current authorized server.
        Ok(())
    }
    /// Single inert canonical GET; population/selection/page and provenance stay server-owned.
    pub async fn bookkeeping_workbench(&self, company: &str, input: &Value) -> Result<Value, Error> {
        Self::validate_bookkeeping_workbench(input)?;
        let owned = input.as_object().unwrap().iter().map(|(k,v)| {
            (k.clone(), v.as_str().map(str::to_owned).unwrap_or_else(|| (v.as_f64().unwrap() as u64).to_string()))
        }).collect::<Vec<_>>();
        let query = owned.iter().map(|(k,v)| (k.as_str(),v.as_str())).collect::<Vec<_>>();
        let selected = if std::path::Path::new(company).is_absolute() {
            let local = self.local.as_ref().ok_or(Error::InvalidInput("absolute company requires explicit verified local profile"))?;
            self.assert_original_workspace89(local.workspace_root().to_str().ok_or(Error::InvalidInput("UTF-8 workspace root required"))?)?;
            let relative = std::path::Path::new(company).strip_prefix(local.workspace_root()).map_err(|_| Error::InvalidInput("company differs from verified workspace root"))?;
            let mut parts = relative.components();
            let Some(std::path::Component::Normal(slug)) = parts.next() else { return Err(Error::InvalidInput("one registered company directory required")); };
            if parts.next().is_some() { return Err(Error::InvalidInput("one registered company directory required")); }
            slug.to_str().ok_or(Error::InvalidInput("UTF-8 company slug required"))?.to_owned()
        } else { company.to_owned() };
        let value = self.batch_json(Method::GET, &company_path(&selected,"bookkeeping-workbench")?, &query, None).await?;
        if value["ok"] == true && !value["workbench"].is_object() {
            return Err(Error::Protocol);
        }
        if value["ok"] == false && !value["errors"].as_array().is_some_and(|a| !a.is_empty() && a.iter().all(Value::is_string)) {
            return Err(Error::Protocol);
        }
        Ok(value)
    }
}
